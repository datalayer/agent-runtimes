/**
 * The frontend tools each UI plugin contributes (`specs/uiFrontendTools`),
 * held to the plugins themselves: each UI spec's plugin mounted and read
 * back, its `agent.chat.extras` frontend tools named as the model sees them
 * and described in their own words. Every one has a description of its own
 * — what it does, not that it runs in the page — and the exported
 * `uiFrontendTools.generated.ts` is exactly what the plugins say.
 *
 * Regenerate the export with
 * `WRITE_UI_FRONTEND_TOOLS=1 npx vitest run src/apps/__tests__/ui-frontend-tools.test.ts`.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it, vi } from 'vitest';

vi.mock('../plugins/notebook-toolbar/items', () => ({
  notebookToolbarItems: () => [],
}));

import './fixtures/notebookTools';
import { FRONTEND_TOOL_CATALOG } from '../../specs/frontendTools';
import { listUI } from '../../specs/ui';
import {
  UI_FRONTEND_TOOLS,
  uiFrontendToolNamed,
  uiFrontendToolsOf,
  type UiFrontendTool,
} from '../../specs/uiFrontendTools';
import { namedFrontendTool } from '../../tools/frontendToolNames';
import { uiPluginManifestOf } from '../uiPluginCatalogue';
import { mountOf, registrationOf } from './fixtures/uiPluginRegistrations';

const GENERATED = join(
  __dirname,
  '..',
  '..',
  'specs',
  'uiFrontendTools.generated.ts',
);

/** What the plugins say: each UI spec's frontend tools, those with any. */
async function collect(): Promise<Record<string, UiFrontendTool[]>> {
  const out: Record<string, UiFrontendTool[]> = {};
  for (const spec of listUI()) {
    const { frontendTools } = await registrationOf(await mountOf(spec));
    if (frontendTools.length === 0) {
      continue;
    }
    out[spec.id] = frontendTools.map(tool => {
      // A tool without words of its own is refused below, not made up here.
      if (!tool.description?.trim()) {
        return { name: namedFrontendTool(tool).name, description: '' };
      }
      // As the model is given it, and as the chat's tools menu shows it.
      const { name, description } = namedFrontendTool(tool);
      return { name, description };
    });
  }
  return out;
}

function render(data: Record<string, UiFrontendTool[]>): string {
  return [
    '/*',
    ' * Copyright (c) 2025-2026 Datalayer, Inc.',
    ' * Distributed under the terms of the Modified BSD License.',
    ' */',
    '',
    '/**',
    ' * The frontend tools each UI plugin contributes, read from the plugins.',
    ' * Read through `specs/uiFrontendTools`.',
    ' *',
    ' * This file is AUTO-GENERATED by src/apps/__tests__/ui-frontend-tools.test.ts.',
    ' * DO NOT EDIT MANUALLY - run it with WRITE_UI_FRONTEND_TOOLS=1 to regenerate.',
    ' *',
    ' * @module specs/uiFrontendTools.generated',
    ' */',
    '',
    "import type { UiFrontendTool } from './uiFrontendTools';",
    '',
    'export const UI_FRONTEND_TOOLS: Record<string, UiFrontendTool[]> = ' +
      JSON.stringify(data, null, 2) +
      ';',
    '',
  ].join('\n');
}

describe('the UI plugins’ frontend tools', () => {
  it('are exported as the plugins say', async () => {
    const data = await collect();
    const text = render(data);
    if (process.env.WRITE_UI_FRONTEND_TOOLS) {
      writeFileSync(GENERATED, text);
    }
    expect(
      readFileSync(GENERATED, 'utf8'),
      'uiFrontendTools.generated.ts is stale: rerun this test with WRITE_UI_FRONTEND_TOOLS=1',
    ).toBe(text);
    expect(UI_FRONTEND_TOOLS).toEqual(data);
  }, 120_000);

  it('each say what they do, in their own words', () => {
    for (const [id, tools] of Object.entries(UI_FRONTEND_TOOLS)) {
      for (const tool of tools) {
        const where = `${id}: ${tool.name}`;
        expect(tool.description.length, where).toBeGreaterThan(40);
        expect(tool.description, where).not.toMatch(
          /^(Runs in (this|the) page|.* runs in the visible application)\.?$/,
        );
      }
    }
  });

  it('name their siblings as the model is given them', () => {
    // jupyter-react and jupyter-lexical write `readAllCells`; the page names
    // it `notebookReadAllCells`, and so do the descriptions it hands over.
    for (const id of ['page-notebook', 'page-document']) {
      const tools = uiFrontendToolsOf(id);
      expect(tools.length, id).toBeGreaterThan(0);
      const bare = tools.map(tool =>
        tool.name.replace(/^(notebook|document)([A-Z])/, (_, __, first) =>
          first.toLowerCase(),
        ),
      );
      for (const tool of tools) {
        for (const reference of bare) {
          expect(tool.description, `${tool.name}: ${reference}`).not.toMatch(
            new RegExp(`\\b${reference}\\b`),
          );
        }
      }
    }
  });

  it('are named once across the plugins', () => {
    const names = Object.values(UI_FRONTEND_TOOLS)
      .flat()
      .map(tool => tool.name);
    expect(names.length).toBe(new Set(names).size);
    for (const name of names) {
      expect(uiFrontendToolNamed(name)?.name).toBe(name);
    }
  });

  it('are the tools of the frontend tool set of the same id', () => {
    for (const [id, tools] of Object.entries(UI_FRONTEND_TOOLS)) {
      const set = FRONTEND_TOOL_CATALOG[id];
      if (!set || set.toolset === 'all') {
        continue;
      }
      expect([...(set.toolset as string[])].sort(), id).toEqual(
        tools.map(tool => tool.name).sort(),
      );
    }
  });

  it('are carried by each UI plugin’s manifest', () => {
    for (const spec of listUI()) {
      expect(
        uiPluginManifestOf(spec.id)?.ui.frontendTools ?? [],
        spec.id,
      ).toEqual(uiFrontendToolsOf(spec.id));
    }
  });
});
