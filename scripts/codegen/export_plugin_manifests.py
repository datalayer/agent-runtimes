"""
Export the protocol and harness plugins' Reactor manifests for the npm package.

Registers the ``agent-protocols`` and ``agent-runtimes`` Reactor Extensions
on a fresh ``PluginPlatform`` — no server, no runtime, no network — and
writes what its ``list_plugins()`` says of the plugins whose manifest carries
a protocol spec (``metadata.protocol``) or a harness spec
(``metadata.harness``): the manifest fields alone (not the platform's state),
sorted by catalogue id, keys sorted. The manifests are filled from the
generated specs (``agent_runtimes.protocols.manifest``,
``agent_runtimes.plugins.harnesses``), so a spec change regenerates them:
``make specs`` runs this after the generators.

Two files, the same data: a JSON for any reader, and a TypeScript module
(``src/specs/pluginManifests.ts`` reads it) so that the library needs no JSON
import. Both are ``*.generated.*``, which prettier leaves as written.

Usage:
    python scripts/codegen/export_plugin_manifests.py \\
      --json-output src/specs/pluginManifests.generated.json \\
      --typescript-output src/specs/pluginManifests.generated.ts

    # Fails, naming the files, when either is not what the specs give.
    python scripts/codegen/export_plugin_manifests.py --check ...
"""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import fields
from pathlib import Path
from typing import Any

from reactor import PluginManifest, PluginPlatform

#: The fields of a manifest, as ``list_plugins()`` spreads it; the rest is the platform's state.
MANIFEST_FIELDS = tuple(field.name for field in fields(PluginManifest))

DESCRIPTION = (
    "The protocol and harness plugins' Reactor manifests, as list_plugins() gives them "
    "(the manifest fields alone), each filled from its spec. AUTO-GENERATED by "
    "scripts/codegen/export_plugin_manifests.py: run 'make specs' to regenerate."
)


def collect() -> dict[str, Any]:
    """The manifests, from a platform holding both extensions."""
    from agent_runtimes.plugins.extension import extension as runtimes_extension
    from agent_runtimes.plugins.harnesses import HARNESS_KEY
    from agent_runtimes.protocols.extension import extension as protocols_extension
    from agent_runtimes.protocols.manifest import PROTOCOL_KEY

    platform = PluginPlatform()
    platform.register_extension_object(protocols_extension())
    platform.register_extension_object(runtimes_extension())
    listed = [
        {name: entry[name] for name in MANIFEST_FIELDS}
        for entry in platform.list_plugins()
    ]

    def of(key: str) -> list[dict[str, Any]]:
        chosen = [entry for entry in listed if key in entry["metadata"]]
        ids = [entry["metadata"][key]["id"] for entry in chosen]
        if len(set(ids)) != len(ids):
            raise ValueError(f"two plugins carry the same {key} spec: {sorted(ids)}")
        return sorted(chosen, key=lambda entry: entry["metadata"][key]["id"])

    return {
        "description": DESCRIPTION,
        "protocols": of(PROTOCOL_KEY),
        "harnesses": of(HARNESS_KEY),
    }


def render_json(data: dict[str, Any]) -> str:
    """The JSON file."""
    return json.dumps(data, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def render_typescript(data: dict[str, Any]) -> str:
    """The TypeScript module: the same data, typed by ``pluginManifests.ts``."""
    return "\n".join(
        [
            "/*",
            " * Copyright (c) 2025-2026 Datalayer, Inc.",
            " * Distributed under the terms of the Modified BSD License.",
            " */",
            "",
            "/**",
            " * The protocol and harness plugins' Reactor manifests, as the Python",
            " * `list_plugins()` gives them. Read through `specs/pluginManifests`.",
            " *",
            " * This file is AUTO-GENERATED by scripts/codegen/export_plugin_manifests.py.",
            " * DO NOT EDIT MANUALLY - run 'make specs' to regenerate.",
            " *",
            " * @module specs/pluginManifests.generated",
            " */",
            "",
            "import type { PluginManifestsExport } from './pluginManifests';",
            "",
            "export const PLUGIN_MANIFESTS: PluginManifestsExport = "
            + json.dumps(data, indent=2, sort_keys=True, ensure_ascii=False)
            + ";",
            "",
        ]
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json-output", type=Path, required=True)
    parser.add_argument("--typescript-output", type=Path, required=True)
    parser.add_argument(
        "--check",
        action="store_true",
        help="write nothing; fail when a file is not what the specs give",
    )
    args = parser.parse_args()
    data = collect()
    wanted = {
        args.json_output: render_json(data),
        args.typescript_output: render_typescript(data),
    }
    if args.check:
        stale = [
            str(path)
            for path, text in wanted.items()
            if not path.is_file() or path.read_text() != text
        ]
        if stale:
            print(
                f"Not what the specs give: {', '.join(stale)}. Run 'make specs-manifests'.",
                file=sys.stderr,
            )
            sys.exit(1)
        print(f"Up to date: {', '.join(str(path) for path in wanted)}")
        return
    for path, text in wanted.items():
        path.write_text(text)
    print(
        f"Exported {len(data['protocols'])} protocol and {len(data['harnesses'])} harness "
        f"manifests: {args.json_output}, {args.typescript_output}"
    )


if __name__ == "__main__":
    main()
